INSERT INTO public.permissions (key, module, resource, action, scope, label_pt, description, is_system)
SELECT
  r.module || '.' || r.resource || '.' || a.action || '.' || a.scope,
  r.module, r.resource, a.action::perm_action, a.scope::perm_scope,
  a.action_pt || ' ' || r.label_pt || ' (' || a.scope_pt || ')',
  NULL, true
FROM res r CROSS JOIN acts a
ON CONFLICT (key) DO NOTHING;

