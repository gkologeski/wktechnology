-- Perfis de sistema de administrador continuam com o catálogo completo.
INSERT INTO public.permission_set_items (set_id, permission_key)
SELECT ps.id, p.key
FROM public.permission_sets ps
JOIN public.permissions p ON (ps.module = 'system' OR p.module = ps.module)
WHERE ps.is_system = true
  AND (ps.name IN ('Admin','Super Admin','Workspace Admin','Workspace Owner') OR ps.name ILIKE '%Admin')
ON CONFLICT DO NOTHING;