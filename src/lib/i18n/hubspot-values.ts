/** Um código herdado do HubSpot (MAIÚSCULA_COM_UNDERSCORE ou minúscula sem espaços). */
function isCodeLike(value: string) {
  return /^[A-Za-z][A-Za-z0-9_]*$/.test(value) && !value.includes(" ");
}

/** Fallback legível: COMPUTER_SOFTWARE -> "Computer Software". */
export function humanizeCode(value: string) {
  return value
    .split(/[_-]+/)
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join(" ");
}

/**
 * Traduz o valor de um campo para PT-BR quando ele é um código conhecido do HubSpot.
 * Valores já em português, textos livres e IDs numéricos (estágios customizados)
 * são devolvidos sem alteração.
 */
export function translateFieldValue(fieldKey: string | null | undefined, value: unknown): string {
  if (value === null || value === undefined) return "";
  const raw = typeof value === "string" ? value : String(value);
  const trimmed = raw.trim();
  if (!trimmed) return "";

  const dict = fieldKey ? DICTIONARIES[fieldKey.toLowerCase()] : undefined;
  if (dict) {
    const direct = dict[trimmed] ?? dict[trimmed.toUpperCase()] ?? dict[trimmed.toLowerCase()];
    if (direct) return direct;
  }

  // IDs numéricos de estágio customizado do HubSpot ficam como estão.
  if (/^\d+$/.test(trimmed)) return trimmed;

  if (dict && isCodeLike(trimmed) && trimmed === trimmed.toUpperCase()) {
    return humanizeCode(trimmed);
  }

  return trimmed;
}

/** Traduz uma lista de opções { value, label } preservando os valores originais. */
export function translateOptions<T extends { value: string; label?: string }>(
  fieldKey: string | null | undefined,
  options: T[],
): Array<T & { label: string }> {
  return options.map((o) => ({
    ...o,
    label: translateFieldValue(fieldKey, o.label ?? o.value) || (o.label ?? o.value),
  }));
}
