const SHARED_CONFIG_RESOURCES = new Set([
  "system.communication.subscription_types",
  "system.roles",
  "system.members",
  "system.branding",
  "system.custom_objects",
  "system.custom_properties",
  "system.settings",
  "system.ai_settings",
  "system.modules",
]);
const prefixes = Object.keys(routes).sort((a, b) => b.length - a.length);
export function salesRouteResources(url: string): readonly string[] | undefined {
  const path = url.split(/[?#]/, 1)[0].replace(/\/$/, "");
  const prefix = prefixes.find((p) => path === p || path.startsWith(p + "/"));
  return prefix ? routes[prefix] : undefined;
}
export function canViewSalesRoute(url: string, permissions: ReadonlySet<string>, ready: boolean) {
  const resources = salesRouteResources(url);
  return (
    !resources ||
    (ready &&
      resources.some((r) =>
        (SHARED_CONFIG_RESOURCES.has(r) ? ["workspace"] : ["own", "team", "workspace"]).some((s) =>
          permissions.has(`${r}.view.${s}`),
        ),
      ))
  );
}
